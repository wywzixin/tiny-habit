export function t(lang: Language, key: string) {
  return (lang === 'en' ? en : zh)[key] || key;
}

export function formatText(lang: Language, key: string, params: Record<string, string | number>) {
  let text = t(lang, key);
  Object.keys(params).forEach((k) => {
    text = text.replace(`{${k}}`, String(params[k]));
  });
  return text;
}

export function getLocale(lang: Language) {
  return lang === 'en' ? 'en-US' : 'zh-CN';
}
